//! The graph: models wired over series, evaluated in dependency order.
//!
//! * Models in one dependency level run in parallel; inside a model, cross-sections run in
//!   parallel across times and time series across entities (when the model allows it).
//! * Every output is cached under a content key: the model's fingerprint, its inputs' versions,
//!   the calendar and the knowledge policy. The same inputs give a bit-identical output (I10), so a
//!   fair-value fit or a Merton model runs once for every strategy and sweep that uses it.
//! * Every state has one producer (spec, change 4). A model's output may be **substituted** by
//!   an observation of the same state, to replay history, but only if nothing upstream of it is
//!   **intervened**: a stress, a counterfactual decision or a simulated world. Interventions
//!   propagate: every series downstream of one carries it, and the run's [`Mode`] follows.

use std::collections::{BTreeMap, HashMap};
use std::fmt;
use std::sync::Arc;

use rayon::prelude::*;

use crate::{
    Error, Result,
    entity::EntityId,
    hash::Hash64,
    model::{CrossSectionModel, Model, ModelSpec, TimeSeriesModel},
    series::{Column, Intervention, KnowledgeBasis, Producer, Provenance, Series, Unit},
    time::{Calendar, Ts},
    workspace::{ModelRecord, Workspace},
};

/// Models to evaluate together.
#[derive(Clone, Default)]
pub struct Graph {
    models: Vec<Model>,
    substitutes: BTreeMap<String, String>,
}

/// What kind of experiment a run is, derived from what it substitutes and intervenes (spec,
/// change 4): the patterns are the brief's run modes, without a field to declare them.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Mode {
    /// Every state is derived from observations: nothing substituted or intervened.
    Derived,
    /// Derived states replaced by observations of them: history replayed.
    Replay,
    /// Values that did not happen: a stress, a scenario series.
    Scenario,
    /// A decision other than the one taken, and everything downstream recomputed.
    Counterfactual,
    /// A world generated by stochastic models.
    Simulation,
}

impl Mode {
    /// The mode an intervention makes.
    #[must_use]
    pub fn of(i: &Intervention) -> Self {
        match i {
            Intervention::Scenario(_) => Self::Scenario,
            Intervention::Counterfactual(_) => Self::Counterfactual,
            Intervention::Simulation(_) => Self::Simulation,
        }
    }
}

impl fmt::Display for Mode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::Derived => "derived",
            Self::Replay => "replay",
            Self::Scenario => "scenario",
            Self::Counterfactual => "counterfactual",
            Self::Simulation => "simulation",
        })
    }
}

/// What an evaluation did.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct GraphReport {
    /// Models computed.
    pub evaluated: Vec<String>,
    /// Models whose output came from the cache.
    pub cached: Vec<String>,
    /// States replaced by observations: (state, observation).
    pub substituted: Vec<(String, String)>,
    /// Models whose outputs are not what happened, and why.
    pub intervened: Vec<(String, Intervention)>,
}

impl GraphReport {
    /// The mode: the strongest intervention, else a replay if anything was substituted.
    #[must_use]
    pub fn mode(&self) -> Mode {
        let strongest = self.intervened.iter().map(|(_, i)| Mode::of(i)).max();
        strongest.unwrap_or(if self.substituted.is_empty() { Mode::Derived } else { Mode::Replay })
    }
}

impl Graph {
    /// An empty graph.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Adds a model.
    pub fn add(&mut self, model: Model) -> &mut Self {
        self.models.push(model);
        self
    }

    /// Replaces the state `state` (a series a model writes) by `observation`, a registered series
    /// describing it: the trustee's reported tranche flows for a deal's computed ones. Refused at
    /// evaluation if anything upstream of the state is intervened.
    pub fn substitute(&mut self, state: &str, observation: &str) -> &mut Self {
        self.substitutes.insert(state.to_owned(), observation.to_owned());
        self
    }

    /// Number of models.
    #[must_use]
    pub fn len(&self) -> usize {
        self.models.len()
    }

    /// Whether the graph has no models.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.models.is_empty()
    }

    /// Evaluates every model on `cal`, writing each output into the workspace as a series named
    /// after the model.
    ///
    /// # Errors
    /// Unknown inputs, duplicate model names, dependency cycles, or a model returning the wrong
    /// number of values.
    pub fn evaluate(&self, ws: &mut Workspace, cal: &Calendar) -> Result<GraphReport> {
        let specs: Vec<ModelSpec> = self.models.iter().map(Model::spec).collect();
        for s in &specs {
            if let Some(n) = s.produced().iter().find(|n| ws.is_registered(n)) {
                return Err(Error::Invalid(format!("model {} writes {n}, the name of a registered series: every state has one producer", s.name)));
            }
        }
        for (state, obs) in &self.substitutes {
            if !specs.iter().any(|s| s.produced().contains(state)) {
                return Err(Error::Unknown(format!("no model writes {state}, so {obs} has nothing to stand in for")));
            }
            if !ws.is_registered(obs) {
                return Err(Error::Unknown(format!("{obs} is not a registered series, so it cannot stand in for {state}")));
            }
        }
        let mut report = GraphReport::default();
        for level in levels(&specs)? {
            let mut todo = Vec::new();
            let mut why: HashMap<usize, Option<Intervention>> = HashMap::new();
            for &i in &level {
                let spec = &specs[i];
                let intervention = self.models[i].intervention(ws).or_else(|| inherited(spec, ws));
                let produced = spec.produced();
                for out in &produced {
                    if let (Some(obs), Some(iv)) = (self.substitutes.get(out), &intervention) {
                        return Err(Error::Invalid(format!(
                            "{obs} cannot stand in for {out}: {out} is downstream of an intervention ({} by {}), so it is derived, not observed",
                            iv.kind(),
                            iv.by()
                        )));
                    }
                }
                if let Some(iv) = &intervention {
                    report.intervened.push((spec.name.clone(), iv.clone()));
                }
                let key = cache_key(spec, ws, cal, intervention.as_ref())?;
                ws.record_model(ModelRecord {
                    name: spec.name.clone(),
                    fingerprint: spec.fingerprint(),
                    key,
                    role: spec.role,
                    shape: spec.shape,
                    available_from: spec.available_from,
                    retrospective: spec.retrospective,
                    vintages: self.models[i].vintages(),
                    writes: produced.clone(),
                    intervention: intervention.clone(),
                    substituted: produced.iter().filter_map(|o| self.substitutes.get(o).map(|s| (o.clone(), s.clone()))).collect(),
                });
                if produced.iter().all(|o| self.substitutes.contains_key(o)) {
                    // Every output is observed: the model does not run.
                    for o in &produced {
                        self.put_observed(ws, o, &mut report)?;
                    }
                    continue;
                }
                let keys: Vec<u64> = (0..produced.len()).map(|j| output_key(key, j)).collect();
                let hits: Option<Vec<Arc<Series>>> = keys.iter().map(|k| ws.cached(*k)).collect();
                if let Some(hits) = hits {
                    for (s, o) in hits.into_iter().zip(&produced) {
                        if self.substitutes.contains_key(o) {
                            self.put_observed(ws, o, &mut report)?;
                        } else {
                            ws.put_derived(s)?;
                        }
                    }
                    report.cached.push(spec.name.clone());
                } else {
                    why.insert(i, intervention);
                    todo.push((i, keys));
                }
            }
            let ws_ref: &Workspace = ws;
            type Out = Result<(usize, Vec<u64>, Vec<Series>)>;
            let one = |(i, keys): &(usize, Vec<u64>)| -> Out { evaluate_one(&self.models[*i], &specs[*i], ws_ref, cal).map(|s| (*i, keys.clone(), s)) };
            let results: Vec<Out> = if todo.len() > 1 && todo.iter().all(|(i, _)| specs[*i].parallel) {
                todo.par_iter().map(one).collect()
            } else {
                todo.iter().map(one).collect()
            };
            for r in results {
                let (i, keys, outs) = r?;
                let intervention = why.remove(&i).flatten();
                for (key, s) in keys.into_iter().zip(outs) {
                    let name = s.name().to_owned();
                    let mut p = s.provenance().clone();
                    if p.intervention.is_none() {
                        p.intervention.clone_from(&intervention);
                    }
                    // A model's output is never an observation, whatever the model wrote.
                    if p.producer == Producer::Observed {
                        p.producer = Producer::Model { name: specs[i].name.clone(), role: specs[i].role };
                        p.knowledge = KnowledgeBasis::Derived;
                        p.describes.get_or_insert_with(|| name.clone());
                    }
                    let s = Arc::new(s.with_provenance(p));
                    ws.cache(key, s.clone());
                    if self.substitutes.contains_key(&name) {
                        self.put_observed(ws, &name, &mut report)?;
                    } else {
                        ws.put_derived(s)?;
                    }
                }
                report.evaluated.push(specs[i].name.clone());
            }
        }
        Ok(report)
    }

    /// Puts the observation that stands in for `state` under its name.
    fn put_observed(&self, ws: &mut Workspace, state: &str, report: &mut GraphReport) -> Result<()> {
        let obs = &self.substitutes[state];
        let s = ws.series(obs)?;
        let mut p = s.provenance().clone();
        p.describes = Some(state.to_owned());
        ws.put_derived(Arc::new(s.renamed(state).with_provenance(p)))?;
        report.substituted.push((state.to_owned(), obs.clone()));
        Ok(())
    }
}

/// The first intervention upstream of a model: in its inputs, relationships, universe or reads.
fn inherited(spec: &ModelSpec, ws: &Workspace) -> Option<Intervention> {
    spec.inputs
        .iter()
        .flat_map(|i| std::iter::once(i.series.as_str()).chain(i.via.as_ref().map(|v| v.0.as_str())))
        .chain(spec.universe.as_deref())
        .chain(spec.reads.iter().map(String::as_str))
        .filter_map(|n| ws.series(n).ok())
        .find_map(|s| s.provenance().intervention.clone())
}

/// Dependency levels: a model depends on another if it reads that model's output.
fn levels(specs: &[ModelSpec]) -> Result<Vec<Vec<usize>>> {
    let produced: Vec<Vec<String>> = specs.iter().map(ModelSpec::produced).collect();
    let mut by_name: HashMap<&str, usize> = HashMap::new();
    for (i, names) in produced.iter().enumerate() {
        for n in names {
            if by_name.insert(n.as_str(), i).is_some() {
                return Err(Error::Invalid(format!("two models write {n}")));
            }
        }
    }
    let deps: Vec<Vec<usize>> = specs
        .iter()
        .map(|s| {
            let mut d: Vec<usize> = s
                .inputs
                .iter()
                .flat_map(|i| std::iter::once(i.series.as_str()).chain(i.via.as_ref().map(|v| v.0.as_str())))
                .chain(s.universe.as_deref())
                .chain(s.reads.iter().map(String::as_str))
                .filter_map(|n| by_name.get(n).copied())
                .collect();
            d.sort_unstable();
            d.dedup();
            d
        })
        .collect();
    let mut level = vec![usize::MAX; specs.len()];
    let mut out: Vec<Vec<usize>> = Vec::new();
    let mut done = 0;
    while done < specs.len() {
        let ready: Vec<usize> = (0..specs.len()).filter(|&i| level[i] == usize::MAX && deps[i].iter().all(|&d| level[d] != usize::MAX)).collect();
        if ready.is_empty() {
            return Err(Error::Invalid("the models' inputs form a cycle".into()));
        }
        for &i in &ready {
            level[i] = out.len();
        }
        done += ready.len();
        out.push(ready);
    }
    Ok(out)
}

fn cache_key(spec: &ModelSpec, ws: &Workspace, cal: &Calendar, intervention: Option<&Intervention>) -> Result<u64> {
    let mut h = Hash64::new();
    h.u64(spec.fingerprint());
    h.str(&format!("{intervention:?}"));
    for i in &spec.inputs {
        h.u64(ws.series(&i.series)?.version());
        if let Some((rel, _)) = &i.via {
            h.u64(ws.series(rel)?.version());
        }
    }
    if let Some(u) = &spec.universe {
        h.u64(ws.series(u)?.version());
    }
    for r in &spec.reads {
        h.u64(ws.series(r)?.version());
    }
    h.u64(cal.version());
    ws.knowledge().hash_into(&mut h);
    Ok(h.finish())
}

/// An input bound to its series.
struct Bound<'a> {
    series: &'a Series,
    col: usize,
    asof: bool,
    market: bool,
    via: Option<(&'a Series, usize)>,
}

impl Bound<'_> {
    fn read(&self, e: EntityId, t: Ts, known_by: Ts) -> f64 {
        if self.market {
            return self.series.asof(self.col, EntityId::NONE, t, known_by).map_or(f64::NAN, |h| h.value);
        }
        let target = match &self.via {
            Some((rel, rc)) => match rel.asof(*rc, e, t, known_by).and_then(|h| EntityId::from_value(h.value)) {
                Some(x) => x,
                None => return f64::NAN,
            },
            None => e,
        };
        let hit = if self.asof { self.series.asof(self.col, target, t, known_by) } else { self.series.exact(self.col, target, t, known_by) };
        hit.map_or(f64::NAN, |h| h.value)
    }
}

fn bind<'a>(spec: &ModelSpec, ws: &'a Workspace) -> Result<(Vec<Bound<'a>>, Vec<EntityId>)> {
    let mut inputs = Vec::with_capacity(spec.inputs.len());
    for i in &spec.inputs {
        let s = ws.series(&i.series)?;
        let via = match &i.via {
            Some((rel, col)) => {
                let r = ws.series(rel)?;
                Some((r.as_ref(), r.column(col)?))
            }
            None => None,
        };
        inputs.push(Bound { series: s.as_ref(), col: s.column(&i.column)?, asof: i.asof, market: i.market, via });
    }
    let universe = match &spec.universe {
        Some(u) => ws.series(u)?.entities(),
        None => spec
            .inputs
            .iter()
            .zip(&inputs)
            .find(|(i, _)| i.via.is_none() && !i.market)
            .map(|(_, b)| b.series.entities())
            .ok_or_else(|| Error::Invalid(format!("model {}: set a universe (every input goes through a relationship)", spec.name)))?,
    };
    Ok((inputs, universe))
}

/// A model's `j`-th output under the model's cache key.
fn output_key(key: u64, j: usize) -> u64 {
    if j == 0 {
        return key;
    }
    let mut h = Hash64::new();
    h.u64(key);
    h.u64(j as u64);
    h.finish()
}

fn evaluate_one(model: &Model, spec: &ModelSpec, ws: &Workspace, cal: &Calendar) -> Result<Vec<Series>> {
    if let Model::Batch(m) = model {
        let outs = m.evaluate(ws, cal)?;
        let names: Vec<&str> = outs.iter().map(Series::name).collect();
        if names != spec.writes.iter().map(String::as_str).collect::<Vec<_>>() {
            return Err(Error::Invalid(format!("model {} wrote {names:?}, but declares {:?}", spec.name, spec.writes)));
        }
        return Ok(outs);
    }
    Ok(vec![evaluate_series(model, spec, ws, cal)?])
}

fn evaluate_series(model: &Model, spec: &ModelSpec, ws: &Workspace, cal: &Calendar) -> Result<Series> {
    if spec.outputs.is_empty() {
        return Err(Error::Invalid(format!("model {} declares no outputs", spec.name)));
    }
    let (inputs, universe) = bind(spec, ws)?;
    let columns = match model {
        Model::CrossSection(m) => cross_section(m.as_ref(), spec, &inputs, &universe, cal)?,
        Model::TimeSeries(m) => time_series(m.as_ref(), spec, &inputs, &universe, cal)?,
        Model::Batch(_) => unreachable!("batch models are evaluated whole"),
    };
    let mut columns = columns;
    // Before a model became available, a point-in-time run has no output from it.
    if let Some(from) = spec.available_from.filter(|_| !spec.retrospective && ws.knowledge().is_point_in_time()) {
        let n = universe.len();
        let before = cal.times().partition_point(|t| *t < from);
        for c in &mut columns {
            c[..before * n].fill(f64::NAN);
        }
    }
    let known = cal.times().iter().map(|t| t.plus(spec.window).plus(spec.lag)).collect();
    let columns = spec.outputs.iter().zip(columns).map(|(n, v)| Column::new(n.clone(), Unit::Number, v)).collect();
    let provenance = Provenance {
        knowledge: KnowledgeBasis::Derived,
        producer: Producer::Model { name: spec.name.clone(), role: spec.role },
        describes: Some(spec.describes.clone().unwrap_or_else(|| spec.name.clone())),
        intervention: None,
    };
    Ok(Series::grid(spec.name.clone(), universe, cal.times().to_vec(), known, columns)?.with_provenance(provenance))
}

fn gather(b: &Bound<'_>, universe: &[EntityId], aligned: bool, t: Ts, known_by: Ts) -> Vec<f64> {
    if aligned {
        // Fast path: an exact read of a grid with the universe's entities, in order.
        return match b.series.grid_time_index(t) {
            Some(ti) if b.series.grid_known(ti) <= known_by => b.series.grid_row(b.col, ti).to_vec(),
            _ => vec![f64::NAN; universe.len()],
        };
    }
    universe.iter().map(|&e| b.read(e, t, known_by)).collect()
}

fn cross_section(m: &dyn CrossSectionModel, spec: &ModelSpec, inputs: &[Bound<'_>], universe: &[EntityId], cal: &Calendar) -> Result<Vec<Vec<f64>>> {
    let aligned: Vec<bool> =
        inputs.iter().map(|b| b.via.is_none() && !b.market && !b.asof && b.series.grid_dims().is_some() && b.series.entities() == universe).collect();
    let one = |t: &Ts| -> Result<Vec<Vec<f64>>> {
        let known_by = t.plus(spec.window);
        let x: Vec<Vec<f64>> = inputs.iter().zip(&aligned).map(|(b, a)| gather(b, universe, *a, *t, known_by)).collect();
        m.compute(*t, universe, &x).map_err(|e| failed(&spec.name, *t, e))
    };
    let rows: Vec<Vec<Vec<f64>>> =
        if spec.parallel { cal.times().par_iter().map(one).collect::<Result<_>>()? } else { cal.times().iter().map(one).collect::<Result<_>>()? };
    let n = universe.len();
    let mut cols: Vec<Vec<f64>> = vec![Vec::with_capacity(cal.len() * n); spec.outputs.len()];
    for (ti, out) in rows.into_iter().enumerate() {
        if out.len() != spec.outputs.len() || out.iter().any(|v| v.len() != n) {
            return Err(Error::Invalid(format!(
                "model {} returned the wrong shape at {}: expected {} outputs of {n} values",
                spec.name,
                cal.times()[ti],
                spec.outputs.len()
            )));
        }
        for (c, v) in cols.iter_mut().zip(out) {
            c.extend(v);
        }
    }
    Ok(cols)
}

/// A model's own error, with the model and the time it failed at.
fn failed(model: &str, t: Ts, e: Error) -> Error {
    match e {
        Error::Invalid(m) => Error::Invalid(format!("model {model} at {t}: {m}")),
        Error::Unknown(m) => Error::Unknown(format!("model {model} at {t}: {m}")),
        Error::Missing(m) => Error::Missing(format!("model {model} at {t}: {m}")),
    }
}

fn time_series(m: &dyn TimeSeriesModel, spec: &ModelSpec, inputs: &[Bound<'_>], universe: &[EntityId], cal: &Calendar) -> Result<Vec<Vec<f64>>> {
    let no = spec.outputs.len();
    let times = cal.times();
    let one = |e: &EntityId| -> Result<Vec<Vec<f64>>> {
        let mut state = m.state();
        let mut out = vec![vec![f64::NAN; times.len()]; no];
        let mut x = vec![f64::NAN; inputs.len()];
        for (ti, t) in times.iter().enumerate() {
            let known_by = t.plus(spec.window);
            for (xi, b) in x.iter_mut().zip(inputs) {
                *xi = b.read(*e, *t, known_by);
            }
            let y = m.step(*t, &x, &mut state).map_err(|err| failed(&spec.name, *t, err))?;
            for (o, col) in out.iter_mut().enumerate() {
                col[ti] = y.get(o).copied().unwrap_or(f64::NAN);
            }
        }
        Ok(out)
    };
    let per_entity: Vec<Vec<Vec<f64>>> =
        if spec.parallel { universe.par_iter().map(one).collect::<Result<_>>()? } else { universe.iter().map(one).collect::<Result<_>>()? };
    let n = universe.len();
    Ok((0..no)
        .map(|o| {
            let mut col = vec![f64::NAN; times.len() * n];
            for (ei, outs) in per_entity.iter().enumerate() {
                for (ti, v) in outs[o].iter().enumerate() {
                    col[ti * n + ei] = *v;
                }
            }
            col
        })
        .collect())
}
